import Foundation

/// Why a pasteboard change was not stored. Safe to log (no content).
public enum SkipReason: Sendable, Equatable {
    case ownWrite
    case concealed
    case ignoredApp
    case tooLarge(bytes: Int)
    case empty

    public var logName: String {
        switch self {
        case .ownWrite: "ownWrite"
        case .concealed: "concealed"
        case .ignoredApp: "ignoredApp"
        case .tooLarge: "tooLarge"
        case .empty: "empty"
        }
    }
}

/// Decides which pasteboard changes are never stored.
public struct SkipRules: Sendable, Equatable {
    /// Marker ClipDock adds to everything it writes, so it doesn't capture itself.
    public static let internalType = "com.omar.clipdock.internal"

    /// nspasteboard.org markers used by password managers and other apps.
    public static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public static let defaultIgnoredBundleIDs: [String] = [
        "com.1password.1password",     // 1Password 8
        "com.agilebits.onepassword7",  // 1Password 7
        "com.bitwarden.desktop",       // Bitwarden
        "com.apple.keychainaccess",    // Keychain Access
        "com.apple.Passwords",         // Passwords
    ]

    public static let defaultMaxBytes = 10 * 1024 * 1024

    public var ignoredBundleIDs: Set<String>
    public var maxBytes: Int

    public init(
        ignoredBundleIDs: [String] = SkipRules.defaultIgnoredBundleIDs,
        maxBytes: Int = SkipRules.defaultMaxBytes
    ) {
        self.ignoredBundleIDs = Set(ignoredBundleIDs.map { $0.lowercased() })
        self.maxBytes = maxBytes
    }

    /// Checked before any content is read, using only the pasteboard types and the source app.
    public func reasonBeforeReading(types: [String], sourceBundleID: String?) -> SkipReason? {
        let typeSet = Set(types)
        if typeSet.contains(Self.internalType) { return .ownWrite }
        if !typeSet.isDisjoint(with: Self.concealedTypes) { return .concealed }
        if let sourceBundleID, ignoredBundleIDs.contains(sourceBundleID.lowercased()) { return .ignoredApp }
        if typeSet.isEmpty { return .empty }
        return nil
    }

    /// Checked on what we would store, after reading and normalizing.
    public func reasonAfterReading(byteSize: Int) -> SkipReason? {
        byteSize > maxBytes ? .tooLarge(bytes: byteSize) : nil
    }
}
